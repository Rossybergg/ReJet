"""Generate loader/core/fs_patches.gen.c: every library instruction that reads an Xbox
KPCR field through fs:, so the loader can redirect it to a Windows TLS slot.

Xbox fs: points at the KPCR; Windows fs: points at the TEB. Both start with the same
NT_TIB fields, so fs:[0] (SEH list, ~1,500 sites, mostly game code) needs nothing. The
rest are ~30 sites in XAPI/DSOUND/CRT code reading fs:[4] (used as the TLS array base),
fs:[0x20] (Prcb), fs:[0x24] (IRQL), fs:[0x28] (current thread) and fs:[0x58]. Each uses a
32-bit displacement, so the loader rewrites only those 4 bytes to point at a TEB TLS slot.

Only addresses, displacement offsets and the original displacement are emitted (no game
bytes); the loader verifies the fs: prefix and old displacement before patching.

    python tools/loader/gen_fs_patches.py
"""
import csv
import struct
import sys
from pathlib import Path

import capstone

ROOT = Path(__file__).resolve().parents[2]
XBE = ROOT / "orig" / "Default.xbe"
FUNCS = ROOT / "config" / "functions.csv"
OUT = ROOT / "loader" / "core" / "fs_patches.gen.c"

SLOTS = {0x04: "FS_SLOT_TLS", 0x20: "FS_SLOT_PRCB", 0x24: "FS_SLOT_IRQL",
         0x28: "FS_SLOT_THREAD", 0x58: "FS_SLOT_DPC"}
LIBRARY = {"xdk", "crt", "adx", "engine"}


def sections(d):
    base = struct.unpack_from("<I", d, 0x104)[0]
    n, sh = struct.unpack_from("<II", d, 0x11C)
    out = []
    for i in range(n):
        _, va, _, raw, rs, _ = struct.unpack_from("<6I", d, sh - base + i * 0x38)
        out.append((va, raw, rs))
    return out


CODE_SECTIONS = {"D3D", "XGRPH", "DSOUND", "XPP", "MMATRIX"}


def library_regions(d):
    """(start, end, origin) of all library code: .text library ranges from config/regions.csv
    plus the library code sections."""
    out = []
    with open(ROOT / "config" / "regions.csv", newline="") as f:
        for r in csv.DictReader(f):
            if r["origin"] in LIBRARY:
                out.append((int(r["start"], 16), int(r["end"], 16), r["origin"]))
    base = struct.unpack_from("<I", d, 0x104)[0]
    n, sh = struct.unpack_from("<II", d, 0x11C)
    for i in range(n):
        _, va, vs, raw, rs, name_va = struct.unpack_from("<6I", d, sh - base + i * 0x38)
        name = d[name_va - base:d.index(b"\0", name_va - base)].decode()
        if name in CODE_SECTIONS or (name.startswith("BINK") and name != "BINKDATA"):
            out.append((va, va + rs, name))
    return out


def main():
    d = XBE.read_bytes()
    secs = sections(d)

    def file_off(va):
        for sva, raw, rs in secs:
            if sva <= va < sva + rs:
                return raw + va - sva
        return None

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    md.skipdata = True  # keep sweeping past bytes that don't decode
    sites, skipped = [], []
    # Linear sweep over every library code region: function lists miss code reached only
    # through callback tables (e.g. XAPI thread-notify routines in the CRT).
    for lo, hi, origin in library_regions(d):
        o = file_off(lo)
        for ins in md.disasm(d[o:o + (hi - lo)], lo):
            if ins.id == 0 or ins.bytes[0] != 0x64:
                continue
            mem = [op for op in ins.operands if op.type == capstone.x86.X86_OP_MEM]
            if not mem or mem[0].mem.base or mem[0].mem.index or mem[0].mem.disp in (0,):
                continue
            disp = mem[0].mem.disp
            if disp not in SLOTS:
                skipped.append(f"{ins.address:#x} {origin} {ins.mnemonic} {ins.op_str}")
                continue
            if ins.disp_size != 4:
                sys.exit(f"{ins.address:#x}: displacement is {ins.disp_size} bytes, expected 4")
            sites.append((ins.address, ins.disp_offset, disp, f"{ins.mnemonic} {ins.op_str}"))

    lines = [
        "/* Generated by tools/loader/gen_fs_patches.py from orig/Default.xbe. Do not edit. */",
        '#include "emu_thread.h"',
        "",
        "const FsPatch g_fs_patches[] = {",
    ]
    for a, off, disp, text in sorted(sites):
        lines.append(f"    {{ 0x{a:08X}, {off}, 0x{disp:02X}, {SLOTS[disp]} }}, /* {text} */")
    lines += ["};", "const unsigned g_fs_patch_count = sizeof g_fs_patches / sizeof g_fs_patches[0];", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(sites)} fs: sites to patch")
    for s in skipped:
        print("  not patched:", s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
