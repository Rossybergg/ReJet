"""Generate loader/core/xdk_addrs.gen.h from config/functions.csv: one #define per named
library function (XbSymbolDatabase / FID names), so HLE patch tables refer to functions by
name and a wrong or missing address shows up at build time, not as a crash.

    XAPILIB::QueryPerformanceCounter at 0x145FF0 -> #define XDK_XAPILIB_QueryPerformanceCounter 0x00145FF0u

Names that occur more than once (FID conflicts, duplicated CRT helpers) are left out.

    python tools/loader/gen_xdk_addrs.py
"""
import csv
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "config" / "functions.csv"
OUT = ROOT / "loader" / "core" / "xdk_addrs.gen.h"
ORIGINS = {"xdk", "crt"}


def macro(name):
    return "XDK_" + re.sub(r"[^0-9A-Za-z]+", "_", name.replace("::", "_")).strip("_")


def main():
    rows = [r for r in csv.DictReader(open(SRC, newline="", encoding="utf-8"))
            if r["origin"] in ORIGINS and not r["name"].startswith(("FUN_", "switchD", "LAB_", "thunk_", "FID_conflict"))]
    count = Counter(macro(r["name"]) for r in rows)
    lines = ["/* Generated by tools/loader/gen_xdk_addrs.py from config/functions.csv. Do not edit. */",
             "#pragma once", ""]
    n = 0
    for r in sorted(rows, key=lambda r: macro(r["name"])):
        m = macro(r["name"])
        if count[m] != 1:
            continue
        lines.append(f"#define {m} 0x{int(r['address'], 16):08X}u /* {r['section']} */")
        n += 1
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{n} addresses -> {OUT.relative_to(ROOT)} ({sum(1 for c in count.values() if c > 1)} duplicate names skipped)")


if __name__ == "__main__":
    main()
