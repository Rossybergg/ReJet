"""Generate loader/core/kernel_imports.gen.c from config/kernel_imports.csv.

Every imported kernel ordinal gets a table entry. Functions implemented in
loader/core/xboxkrnl_impl.h (declared as xbox_<Name>) point at the implementation; other
function imports get a stub that reports the call (ordinal, caller, stack) to
kernel_unimplemented(); data imports (kernel variables the game reads through the thunk
slot) get a zeroed backing block.

    python tools/loader/gen_kernel.py
"""
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "config" / "kernel_imports.csv"
OUT = ROOT / "loader" / "core" / "kernel_imports.gen.c"
IMPL = ROOT / "loader" / "core" / "xboxkrnl_impl.h"

# Kernel exports that are variables, not functions (by name).
DATA_EXPORTS = {
    "ExEventObjectType", "ExMutantObjectType", "ExSemaphoreObjectType", "ExTimerObjectType",
    "HalDiskCachePartitionCount", "HalDiskModelNumber", "HalDiskSerialNumber",
    "IoCompletionObjectType", "IoDeviceObjectType", "IoFileObjectType",
    "KdDebuggerEnabled", "KdDebuggerNotPresent", "KeTickCount", "KeTimeIncrement",
    "KiBugCheckData", "LaunchDataPage", "MmGlobalData", "ObDirectoryObjectType",
    "ObpObjectHandleTable", "ObSymbolicLinkObjectType", "PsThreadObjectType",
    "XboxEEPROMKey", "XboxHardwareInfo", "XboxHDKey", "XboxKrnlVersion",
    "XboxSignatureKey", "XboxLANKey", "XboxAlternateSignatureKeys", "XePublicKeyData",
    "XeImageFileName", "IdexChannelObject", "HalBootSMCVideoMode",
}


DECL = re.compile(r"(__declspec\(noreturn\)\s+)?(\w[\w ]*?\**)\s+(XBAPI|FASTCALL|__cdecl)\s+xbox_(\w+)\s*\(([^;]*?)\)\s*;",
                  re.S)


def trace_wrapper(ret, conv, name, params):
    """A wrapper that calls xbox_<name> and logs result and caller (REJET_TRACE=1)."""
    plist = [p.strip() for p in params.split(",")]
    names = [] if plist == ["void"] else [re.findall(r"\w+", p)[-1] for p in plist]
    call = f"xbox_{name}({', '.join(names)})"
    head = f"static {ret} {conv} ktw_{name}({', '.join(plist)})"
    if ret.strip() in ("VOID", "void"):
        body = f"{call}; ktrace_call(\"{name}\", _ReturnAddress(), 0, 0);"
    else:
        body = (f"{ret} r = {call}; ktrace_call(\"{name}\", _ReturnAddress(), 1, (unsigned long long)r); "
                f"return r;")
    return f"{head} {{ {body} }}"


def main():
    with open(SRC, newline="") as f:
        rows = [(int(r["ordinal"]), r["name"]) for r in csv.DictReader(f)]
    rows = sorted(set(rows))
    header = IMPL.read_text(encoding="utf-8")
    impl = set(re.findall(r"\bxbox_(\w+)\s*\(", header))
    unknown = impl - {n for _, n in rows}
    if unknown:  # carried over from ReWhacked; harmless, they are just never linked into the thunk table
        print(f"note: implemented but not imported by this XBE: {', '.join(sorted(unknown))}")
    wrappers = {}
    for noreturn, ret, conv, name, params in DECL.findall(header):
        if not noreturn and "..." not in params:
            wrappers[name] = trace_wrapper(ret, conv, name, params)

    out = [
        "/* Generated by tools/loader/gen_kernel.py from config/kernel_imports.csv. Do not edit. */",
        '#include "kernel.h"',
        '#include "xboxkrnl_impl.h"',
        "#include <intrin.h>",
        "",
    ]
    for o, name in rows:
        if name in DATA_EXPORTS:
            out.append(f"static unsigned char kdata_{o}[KERNEL_DATA_BLOCK]; /* {name} */")
        elif name not in impl:
            out.append(f"static void __cdecl kstub_{o}(void) "
                       f"{{ kernel_unimplemented({o}, _ReturnAddress(), _AddressOfReturnAddress()); }}")
        elif name in wrappers:
            out.append(wrappers[name])
    out += ["", "const KernelImport g_kernel_imports[] = {"]
    for o, name in rows:
        if name in DATA_EXPORTS:
            target = traced = f"kdata_{o}"
        elif name in impl:
            target = f"(void *)xbox_{name}"
            traced = f"(void *)ktw_{name}" if name in wrappers else target
        else:
            target = traced = f"(void *)kstub_{o}"
        out.append(f'    {{ {o}, "{name}", {target}, {traced}, {1 if name in DATA_EXPORTS else 0} }},')
    out += ["};", "const unsigned g_kernel_import_count = sizeof g_kernel_imports / sizeof g_kernel_imports[0];", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    data = [n for _, n in rows if n in DATA_EXPORTS]
    print(f"{len(rows)} imports: {len(impl)} implemented, {len(rows) - len(data) - len(impl)} stubbed, "
          f"{len(data)} data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
