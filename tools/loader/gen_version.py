"""Generate loader/core/version.gen.h: ReJet's version for the menu, logs, captures and the
Windows version resource.

The version is semantic (MAJOR.MINOR.PATCH, in the VERSION file at the repository root; bump it
for every build given to testers). The build string adds the git commit, and "-dirty" when the
working tree had uncommitted changes, so a log always says exactly what code produced it:
    0.1.0+3437d69          a release built from a clean commit
    0.1.0+3437d69-dirty    a development build

    python tools/loader/gen_version.py
"""
import datetime
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "loader" / "core" / "version.gen.h"


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def main():
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?", version)
    if not m:
        raise SystemExit(f"VERSION is not a semantic version: {version!r}")
    commit = git("rev-parse", "--short=7", "HEAD") or "nogit"
    dirty = "-dirty" if git("status", "--porcelain", "--untracked-files=no") else ""
    build = f"{version}+{commit}{dirty}"
    date = datetime.date.today().isoformat()
    text = "\n".join([
        "/* Generated by tools/loader/gen_version.py from VERSION and git. Do not edit. */",
        "#pragma once",
        f'#define REJET_VERSION "{version}"',
        f"#define REJET_VERSION_MAJOR {m.group(1)}",
        f"#define REJET_VERSION_MINOR {m.group(2)}",
        f"#define REJET_VERSION_PATCH {m.group(3)}",
        f'#define REJET_BUILD "{build}"',
        f'#define REJET_BUILD_DATE "{date}"',
        "",
    ])
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8")
    print(f"version: {build}")


if __name__ == "__main__":
    main()
